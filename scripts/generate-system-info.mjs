import { createHash } from "node:crypto";
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrations = [];
for (const name of (
  await readdir(path.join(root, "prisma/migrations"))
).sort()) {
  if (!/^\d{3}_[a-z0-9_]+$/.test(name)) continue;
  const sql = await readFile(
    path.join(root, "prisma/migrations", name, "migration.sql"),
  );
  migrations.push({
    name,
    checksum: createHash("sha256").update(sql).digest("hex"),
  });
}
const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
let revision = process.env.GITHUB_SHA || "unknown";
let localChanges = false;
try {
  if (revision === "unknown")
    revision = execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  localChanges = Boolean(
    execFileSync("git", ["status", "--porcelain", "--untracked-files=no"], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim(),
  );
} catch {
  /* Revision is optional in source archives. */
}
if (!/^[a-f0-9]{40}$/.test(revision)) revision = "unknown";
const metadata = {
  version: pkg.version,
  revision,
  localChanges,
  generatedAt: new Date().toISOString(),
  migrations,
};
await mkdir(path.join(root, "src/generated"), { recursive: true });
await writeFile(
  path.join(root, "src/generated/system-info.ts"),
  `// Generated by scripts/generate-system-info.mjs; contains no environment values.\nexport const systemBuild = ${JSON.stringify(metadata, null, 2)} as const;\n`,
);
console.log(
  `System information manifest generated for ${migrations.length} migrations.`,
);
